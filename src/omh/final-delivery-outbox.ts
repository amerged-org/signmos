import { createTransactionalMailClient } from "@ohmyhost/customer-runtime/mail";
import { sql } from "drizzle-orm";
import { z } from "zod";
import { noEnvelopeDeletion, signingStatement } from "@/db/envelope/signing-batch";
import { getDb } from "@/db/setup";
import { renderBrandedEmail } from "@/lib/branded-email";
import { hasOmhMail, type OmhMailEnv } from "./mail";

interface FinalDeliveryEnv extends OmhMailEnv {
	APP_BASE_URL?: string;
}
export interface OutboxProgress {
	processed: number;
	stopped: boolean;
}
const ClaimSchema = z.object({
	id: z.uuid(),
	envelope_id: z.uuid(),
	status: z.enum(["sending", "manual_review"]),
	to_email: z.string(),
	from_email: z.string(),
	reply_to_email: z.string().nullable(),
	access_url: z.url(),
	subject: z.string(),
	text_body: z.string(),
	html_body: z.string(),
});
type Claim = z.infer<typeof ClaimSchema>;
const URL_SLOT = "https://final-delivery.invalid/access";

/** Shares the scheduler's three-job allowance with invitations; no network spans a transaction. */
export async function processFinalDeliveries(
	env: FinalDeliveryEnv,
	budget = 3,
): Promise<OutboxProgress> {
	if (budget <= 0) return { processed: 0, stopped: false };
	if (!hasOmhMail(env) || !env.APP_BASE_URL) return { processed: 0, stopped: true };
	const origin = new URL(env.APP_BASE_URL).origin;
	if (!/^https?:\/\//.test(origin)) throw new Error("Final delivery origin is invalid");
	const template = finalMailTemplate();
	for (let processed = 0; processed < Math.min(budget, 3); processed++) {
		const job = await claim(env, origin, template);
		if (!job) return { processed, stopped: false };
		if (job.status === "manual_review") continue;
		let recording = false;
		try {
			await send(env, job);
			recording = true;
			await getDb().batch([
				signingStatement(
					sql`update contract_final_delivery_outbox set status = 'delivered', updated_at = now() where id = ${job.id} and status = 'sending'`,
				),
				signingStatement(sql`insert into audit_events (envelope_id, event_type, message)
     select ${job.envelope_id}, 'final.delivery.sent', ${job.to_email}
     where exists (select 1 from contract_final_delivery_outbox where id = ${job.id} and status = 'delivered')`),
			]);
		} catch {
			// A lost receipt may already be committed. Leave it for lease recovery, with the same key.
			if (!recording)
				await getDb().execute(
					sql`update contract_final_delivery_outbox set status = 'uncertain', updated_at = now() where id = ${job.id} and status = 'sending'`,
				);
			return { processed: processed + 1, stopped: true };
		}
	}
	return { processed: Math.min(budget, 3), stopped: false };
}

async function claim(
	env: FinalDeliveryEnv,
	origin: string,
	template: ReturnType<typeof finalMailTemplate>,
): Promise<Claim | null> {
	const url = sql`coalesce(job.access_url, ${origin} || job.access_path)`;
	// The path is generated by this application. Escape the URL for the HTML attribute anyway.
	const htmlUrl = sql`replace(replace(replace(replace(replace(${url}, '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), '"', '&quot;'), ${"'"}, '&#39;')`;

	const rows = await getDb().execute(sql`update contract_final_delivery_outbox job set
  status = case when job.first_attempt_at <= now() - interval '22 hours' then 'manual_review' else 'sending' end,
  from_email = case when job.first_attempt_at is null then ${env.SIGN_FROM_EMAIL} else job.from_email end,
  reply_to_email = case when job.first_attempt_at is null then ${env.SIGN_REPLY_TO_EMAIL ?? null} else job.reply_to_email end,
  access_url = ${url},
  subject = case when job.first_attempt_at is null then ${template.subject} else job.subject end,
  text_body = case when job.first_attempt_at is null then replace(${template.text}, ${URL_SLOT}, ${url}) else job.text_body end,
  html_body = case when job.first_attempt_at is null then replace(${template.html}, ${URL_SLOT}, ${htmlUrl}) else job.html_body end,
  first_attempt_at = coalesce(job.first_attempt_at, now()), claimed_at = now(), updated_at = now()
  where job.id = (
   select candidate.id from contract_final_delivery_outbox candidate
   join envelopes e on e.id = candidate.envelope_id
   join final_documents f on f.id = candidate.final_document_id and f.envelope_id = e.id and f.sha256 = candidate.final_sha256
   where (candidate.status = 'queued' or (candidate.status in ('sending', 'uncertain') and candidate.claimed_at < now() - interval '10 minutes'))
   and e.status = 'completed' and ${noEnvelopeDeletion(sql`e.id`)}
   and not exists (select 1 from envelope_recipients r where r.envelope_id = e.id and r.status <> 'completed')
   order by candidate.created_at, candidate.id for update of candidate skip locked limit 1
  ) returning job.id, job.envelope_id, job.status, job.to_email, job.from_email, job.reply_to_email, job.access_url, job.subject, job.text_body, job.html_body`);
	return rows[0] ? ClaimSchema.parse(rows[0]) : null;
}

async function send(env: FinalDeliveryEnv, job: Claim): Promise<void> {
	if (!env.OHMYHOST_MAIL_GATEWAY_URL || !env.OHMYHOST_MAIL_KEY || !env.OHMYHOST_PROJECT_ID)
		throw new Error("Mail unavailable");
	const client = createTransactionalMailClient({
		endpoint: env.OHMYHOST_MAIL_GATEWAY_URL,
		key: env.OHMYHOST_MAIL_KEY,
		projectId: env.OHMYHOST_PROJECT_ID,
		fetch: (request) => fetch(request),
	});
	const mail = {
		from: job.from_email,
		...(job.reply_to_email ? { replyTo: job.reply_to_email } : {}),
		to: job.to_email,
		subject: job.subject,
		text: job.text_body,
		html: job.html_body,
		idempotencyKey: `sign.final.${job.id}`,
	};
	const response = await client.send(mail);
	if (response.state !== "accepted") throw new Error("Mail delivery is uncertain");
}

/** Canonical content is snapshotted by the claim before the first network attempt. */
function finalMailTemplate() {
	return {
		subject: "Dein unterschriebener Vertrag ist bereit · amerged Sign",
		text: `Alle Parteien haben unterschrieben. Dein fertiges PDF ist über deinen persönlichen, geschützten Zugang verfügbar:\n${URL_SLOT}\n\nBestätige bei Bedarf deine E-Mail-Adresse.\n\namerged Sign`,
		html: renderBrandedEmail({
			eyebrow: "VERTRAG ABGESCHLOSSEN",
			title: "Dein Vertrag ist bereit",
			paragraphs: [
				"Alle Parteien haben unterschrieben. Über deinen persönlichen, geschützten Zugang kannst du das fertige PDF herunterladen.",
			],
			action: { label: "Unterschriebenen Vertrag öffnen", url: URL_SLOT },
			note: "Bestätige bei Bedarf deine E-Mail-Adresse.",
		}),
	};
}
