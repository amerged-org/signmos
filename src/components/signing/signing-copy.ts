export type SigningLanguage = keyof typeof signingCopy;

export function signingError(language: SigningLanguage, code?: string): string {
	const copy = signingCopy[language];
	switch (code) {
		case "INVALID_EMAIL_CODE":
			return copy.codeRejected;
		case "EMAIL_CODE_RATE_LIMITED":
			return copy.codeRateLimited;
		case "EMAIL_DELIVERY_UNAVAILABLE":
			return copy.codeDeliveryFailed;
		case "EMAIL_VERIFICATION_UNAVAILABLE":
			return copy.codeUnavailable;
		case "TOKEN_NOT_FOUND":
		case "PARTNER_VERIFICATION_NOT_FOUND":
			return copy.linkMissing;
		case "EXPIRED_TOKEN":
		case "EXPIRED_PARTNER_VERIFICATION":
		case "ENVELOPE_EXPIRED":
		case "HISTORY_SIGNING_EXPIRED":
			return copy.linkExpired;
		case "ENVELOPE_DELETED":
		case "HISTORY_SIGNING_DELETED":
			return copy.deleted;
		case "HISTORY_SIGNING_DECLINED":
			return copy.declined;
		case "PARTNER_VERIFICATION_REQUIRED":
			return copy.verificationRequired;
		case "SIGNING_BLOCKED":
			return copy.signingBlocked;
		case "INVALID_SIGNING_COMPLETION":
			return copy.invalidFields;
		case "NO_ASSIGNED_FIELDS":
			return copy.noAssigned;
		case "FINAL_PDF_GENERATION_FAILED":
			return copy.pdfRetry;
		default:
			return copy.genericError;
	}
}
